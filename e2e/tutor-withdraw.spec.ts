import {test,expect} from '@playwright/test'
const button=(p:any,text:string)=>p.locator('uni-button').filter({hasText:text})
test('家教表单可滚动，政史地可提交，待审核可撤回保留资料再送审',async({page},info)=>{
 const api=info.project.name.startsWith('api')
 await page.goto('/#/pages/auth/login?role=tutor')
 if(api){await page.locator('.credentials input').nth(0).fill('demo.tutor');await page.locator('.credentials input').nth(1).fill(process.env.E2E_PASSWORD!)}
 else await page.locator('.role').filter({hasText:'大学生家教'}).click()
 await button(page,api?'登录开发账户':'进入演示模式').click()
 await expect(button(page,api?'退出登录':'退出演示身份')).toBeVisible()
 await page.goto('/#/pages/tutor/application')
 const field=(text:string)=>page.locator('uni-input,uni-textarea').filter({has:page.getByText(text,{exact:true})}).locator('input,textarea')
 await field('例如：演示老师').fill('政史地演示老师')
 await field('例如：示例大学').fill('示例大学')
 await field('例如：数学与应用数学').fill('人文教育')
 for(const subject of ['思想政治','地理','历史'])await page.locator('.b-chip').filter({hasText:new RegExp('^'+subject+'$')}).click()
 await field('例如：示例大学城').fill('雁塔区 · 小寨')
 await field('填写 1–1000 元').fill('80');await field('例如：周末下午').fill('周末下午')
 await field('介绍虚构的教学经历与特点').fill('虚构资料，以知识结构梳理和课堂练习帮助理解政史地。')
 expect(await page.locator('.application-scroll .uni-scroll-view').nth(1).evaluate(el=>el.scrollHeight>el.clientHeight)).toBe(true)
 await page.locator('.application-footer .b-button:not(.secondary)').click();await page.locator('.uni-modal__btn_primary').click()
 await expect(page.locator('.b-status')).toContainText('待审核')
 await button(page,'撤回申请并修改').click();await page.locator('.uni-modal__btn_default').click()
 await expect(page.locator('.b-status')).toContainText('待审核')
 await button(page,'撤回申请并修改').click();await page.locator('.uni-modal__btn_primary').click()
 await expect(page.locator('.b-status')).toContainText('草稿')
 await expect(field('例如：演示老师')).toHaveValue('政史地演示老师')
 for(const subject of ['思想政治','地理','历史'])await expect(page.locator('.b-chip.active').filter({hasText:new RegExp('^'+subject+'$')})).toHaveCount(1)
 await page.screenshot({path:'docs/screenshots/ui-polish/application-'+info.project.name+'.jpg',quality:80})
 await field('介绍虚构的教学经历与特点').fill('修改后的虚构资料，围绕政史地主题训练和错题复习展开教学。')
 await button(page,'提交审核').click();await page.locator('.uni-modal__btn_primary').click()
 await expect(page.locator('.b-status')).toContainText('待审核')
})
