test('账户订单从真实API读取，自动同步家教接单并支持手动刷新取消',async({page,request},info)=>{
 test.skip(!info.project.name.startsWith('api'),'跨角色状态使用临时API')
 await page.route('https://server.arcgisonline.com/**',r=>r.abort())
 const origin=info.project.name==='api-mobile'?'http://127.0.0.1:3002':'http://127.0.0.1:3001'
 const login=async(role:string)=>{const r=await request.post(origin+'/api/auth/login',{data:{loginId:'e2e.map.'+role,password:process.env.E2E_PASSWORD}});expect(r.status()).toBe(200);return(await r.json()).data.token}
 const parent=await login('parent'),tutor=await login('tutor')
 const headers=(token:string)=>({authorization:'Bearer '+token})
 const t=await request.get(origin+'/api/tutors/me',{headers:headers(tutor)});const profile=(await t.json()).data
 const created=await request.post(origin+'/api/bookings',{headers:headers(parent),data:{tutorId:profile.id,studentName:'不可显示的地图同学',subject:'数学',expectedTime:'周末自动刷新验收',note:'不可显示的私人备注',areaLabel:'高新区 · 科技路'}})
 expect(created.status()).toBe(200);const order=(await created.json()).data
 await fixtureLogin(page,'e2e.map.parent')
 await page.goto('/#/pages/order-map/index')
 await expect(page.locator('.map-order-card')).toContainText('待家教确认')
 await expect(page.locator('.order-map-page')).not.toContainText('不可显示')
 const accepted=await request.post(origin+'/api/bookings/'+order.id+'/accept',{headers:headers(tutor),data:{}});expect(accepted.status()).toBe(200)
 await expect(page.locator('.map-order-card')).toContainText('家教已接受',{timeout:22000})
 const cancelled=await request.post(origin+'/api/bookings/'+order.id+'/cancel',{headers:headers(parent),data:{}});expect(cancelled.status()).toBe(200)
 await button(page,'刷新订单').click();await expect(page.locator('.map-order-card')).toContainText('预约已取消')
 await page.goto('/#/pages/profile/index');await button(page,'退出登录').click()
 await page.goto('/#/pages/order-map/index');await expect(page.locator('.map-order-card')).toHaveCount(0)
 await expect(page.getByText('请先登录，再查看属于当前账户的订单。',{exact:true})).toBeVisible()
})
