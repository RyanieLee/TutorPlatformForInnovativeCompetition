import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const button=(page:import('@playwright/test').Page,text:string)=>page.locator('uni-button').filter({hasText:text})
test('学习中心：笔记筛选、示例自测与有无答案导出',async({page},info)=>{
 const pageErrors:string[]=[];page.on('pageerror',error=>pageErrors.push(error.message))
 await page.goto('/#/pages/index/index')
 await button(page,'AI学习中心 · 各科笔记与智能出卷').click()
 await expect(page.getByText('先学一个知识点，再练一份专属卷。')).toBeVisible()
 await expect(page.locator('.note-card')).toContainText('一元一次方程')
 await page.locator('.selection .chips').first().getByText('高中',{exact:true}).click()
 await page.locator('.subjects').getByText('物理',{exact:true}).click()
 await expect(page.locator('.note-card')).toContainText('牛顿第二定律')
 await expect(page.locator('.source-card')).toHaveCount(4)
 await button(page,'围绕这份笔记出一张卷').click()
 await button(page,'先体验3道原创示例题').click()
 await expect(page.locator('.paper')).toContainText('原创示例题库 · 未调用AI')
 await expect(page.locator('.question')).toHaveCount(3)
 await expect(page.locator('.answer')).toHaveCount(0)
 await page.locator('.question').nth(0).locator('.options uni-button').nth(1).click()
 await page.locator('.question').nth(1).locator('.options uni-button').nth(2).click()
 await button(page,'核对选择题并查看解析').click()
 await expect(page.locator('.feedback')).toContainText('得分 10 / 10')
 const downloadPromise=page.waitForEvent('download')
 await button(page,'导出无答案卷').click()
 const download=await downloadPromise
 expect(download.suggestedFilename()).toContain('无答案')
 await button(page,'隐藏答案与解析').click()
 await expect(page.locator('.answer')).toHaveCount(0)
 mkdirSync('docs/screenshots',{recursive:true})
 const screenshot=`docs/screenshots/learning-${info.project.name}.png`
 await page.screenshot({path:screenshot,fullPage:true})
 await info.attach('学习中心实际页面',{path:screenshot,contentType:'image/png'})
 expect(pageErrors).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
test('AI出卷：登录、结构化结果与失败后保留示例入口',async({page},info)=>{
 test.skip(!info.project.name.startsWith('api'),'真实模型入口仅API模式')
 await page.route('**/api/learning/status',route=>route.fulfill({json:{data:{enabled:true}}}))
 // This UI-only login is isolated from the shared demo account's rate limit.
 const user={id:'browser-exam-parent',displayName:'虚构出卷测试家长',role:'parent'}
 await page.route('**/api/auth/login',route=>route.fulfill({json:{data:{token:'browser-exam-test-token',user}}}))
 await page.route('**/api/auth/me',route=>route.fulfill({json:{data:user}}))
 await page.goto('/#/pages/learning/index')
 await page.locator('.top-tabs').getByText('AI生成试卷',{exact:true}).click()
 await button(page,'AI生成新试卷').click()
 await expect(page.getByText('请先登录演示账户，再返回此页生成AI试卷')).toBeVisible()
 await button(page,'前往登录').click()
 await page.locator('input').nth(0).fill('demo.parent')
 await page.locator('input').nth(1).fill(process.env.E2E_PASSWORD!)
 const loginResponse=page.waitForResponse(r=>r.url().endsWith('/api/auth/login'))
 await button(page,'登录开发账户').click()
 expect((await loginResponse).status()).toBe(200)
 await expect(button(page,'AI生成新试卷')).toBeVisible()
 await page.goto('/#/pages/learning/index')
 await page.locator('.top-tabs').getByText('AI生成试卷',{exact:true}).click()
 const questions=Array.from({length:5},(_,i)=>({id:`q${i+1}`,type:'choice',stem:`测试方程x+${i+1}=${i+3}，x等于多少？`,options:['1','2','3','4'],answer:'B',explanation:'等式两边同时减去相同的数，得到x=2。',points:5}))
 await page.route('**/api/learning/exams',route=>route.fulfill({json:{data:{title:'模型测试试卷',topicId:'topic-06',grade:'七年级',difficulty:'基础',questions,totalPoints:25,source:'model',createdAt:new Date().toISOString()}}}))
 await button(page,'AI生成新试卷').click()
 await expect(page.locator('.paper')).toContainText('AI生成 · 待核对')
 await expect(page.locator('.question')).toHaveCount(5)
 await page.unroute('**/api/learning/exams')
 await page.route('**/api/learning/exams',route=>route.fulfill({status:502,json:{error:{code:'MODEL_UPSTREAM',message:'模型服务测试失败'}}}))
 await button(page,'AI生成新试卷').click()
 await expect(page.locator('.error')).toContainText('模型服务测试失败')
 await expect(page.locator('.paper')).toHaveCount(0)
 await button(page,'先体验3道原创示例题').click()
 await expect(page.locator('.paper')).toContainText('未调用AI')
})
