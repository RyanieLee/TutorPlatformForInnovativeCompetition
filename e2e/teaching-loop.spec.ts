import {test,expect,type Page} from '@playwright/test'
import {mkdirSync} from 'node:fs'
const go=(p:Page,path:string)=>p.goto('/#/pages/'+path)
const button=(p:Page,text:string)=>p.locator('uni-button').filter({hasText:text})
const confirm=(p:Page)=>p.locator('.uni-modal__btn_primary').click()
const field=(p:Page,text:string)=>p.locator('uni-input,uni-textarea').filter({has:p.getByText(text,{exact:true})}).locator('input,textarea')
async function login(p:Page,role:'parent'|'tutor',api:boolean){
 await go(p,'profile/index')
 const logout=button(p,api?'退出登录':'退出演示身份');if(await logout.isVisible())await logout.click()
 await button(p,'演示登录').click()
 if(api){await field(p,'账户 ID').fill('demo.'+role);await field(p,'密码').fill(process.env.E2E_PASSWORD!)}
 else await p.locator('.role').filter({hasText:role==='parent'?'学生 / 家长':'大学生家教'}).click()
 const response=api?p.waitForResponse(r=>r.url().endsWith('/api/auth/login')&&r.request().method()==='POST'):null
 await button(p,api?'登录开发账户':'进入演示模式').click();if(response)expect((await response).status()).toBe(200)
 await expect(button(p,api?'退出登录':'退出演示身份')).toBeVisible()
}
