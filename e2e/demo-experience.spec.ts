import {test,expect,type Page} from '@playwright/test'
import {mkdirSync} from 'node:fs'
const button=(p:Page,text:string)=>p.locator('uni-button').filter({hasText:text})
test('AI入口、问答首屏、更多工具和示例不会自动发送',async({page},info)=>{
 await page.route('**/api/assistant/status',r=>r.fulfill({json:{data:{enabled:false}}}))
 await page.route('**/api/assistant/homework-review/status',r=>r.fulfill({json:{data:{enabled:false,maxImageBytes:3145728,acceptedTypes:['image/png']}}}))
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/#/pages/index/index')
 const cta=page.locator('.hero-cta');await expect(cta).toContainText('AI')
 if(info.project.name.endsWith('mobile'))expect(await cta.evaluate(el=>{const r=el.getBoundingClientRect();return r.bottom<=innerHeight})).toBe(true)
 expect(await cta.evaluate(el=>{const r=el.getBoundingClientRect();const hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);return hit===el||el.contains(hit)})).toBe(true)
 mkdirSync('docs/screenshots',{recursive:true})
 await page.screenshot({path:`docs/screenshots/audit-home-${info.project.name}.png`,fullPage:false})
 await cta.click();await expect(page).toHaveURL(/starter=match/)
 await expect(page.locator('.companion-compose textarea')).toHaveValue('请帮我匹配初中数学，预算100元，线上，周六下午')
 await expect(page.locator('.companion-message.user')).toHaveCount(0)
 await expect(page.locator('.homework-image-tools')).toHaveCount(0)
 if(info.project.name.endsWith('mobile'))await page.setViewportSize({width:375,height:667})
 expect(await page.locator('.companion-compose').evaluate(el=>{const r=el.getBoundingClientRect();return r.bottom<=innerHeight&&r.top>=0})).toBe(true)
 expect(await button(page,'语音提问').evaluate(el=>el.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
 await page.screenshot({path:`docs/screenshots/audit-assistant-${info.project.name}.png`,fullPage:false})
 await button(page,'图片与学习工具').click();await expect(page.locator('.homework-image-tools')).toBeVisible()
 await expect(page.locator('.homework-image-submit')).toBeDisabled()
 await button(page,'收起更多工具').click()
 await page.locator('.companion-compose uni-button').click();await expect(page.locator('.match-card').first()).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect(errors).toEqual([])
})
test('演示导航串起匹配、订单地图、知识点和真实家教工作台',async({page},info)=>{
 await page.route('**/api/assistant/status',r=>r.fulfill({json:{data:{enabled:false}}}))
 await page.route('**/api/assistant/homework-review/status',r=>r.fulfill({json:{data:{enabled:false,maxImageBytes:3145728,acceptedTypes:['image/png']}}}))
 await page.route('https://server.arcgisonline.com/**',r=>r.abort())
 await page.goto('/#/pages/demo/index')
 await expect(page.locator('.demo-step')).toHaveCount(5)
 await expect(page.locator('.demo-status')).toContainText('未配置')
 await expect(page.locator('.demo-page')).toContainText('60%仅指虚构案例')
 mkdirSync('docs/screenshots',{recursive:true});await page.screenshot({path:`docs/screenshots/audit-demo-${info.project.name}.png`,fullPage:true})
 await button(page,'带入匹配示例').click()
 await button(page,'生成推荐').click();await expect(page.locator('.match-card').first()).toContainText('学科吻合：数学')
 await expect(page.locator('.results')).toContainText('初中（演示）')
 await page.goto('/#/pages/demo/index');await button(page,'打开订单地图示例').click()
 await expect(page.locator('.map-order-card')).toHaveCount(12)
 await expect(page.locator('.map-data-note')).toContainText('固定12条虚构示例')
 await page.goto('/#/pages/demo/index');await button(page,'打开知识点示例').click()
 await expect(page.locator('.learning-page')).toBeVisible()
 await expect(page.getByText('一元一次方程',{exact:true}).first()).toBeVisible()
 await page.goto('/#/pages/demo/index');await button(page,'前往家教工作台').click()
 await expect(page.getByText('请先登录家教演示账户',{exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
